// Bundles hls.js (Apache-2.0) into a TS module so the radio's web player works without a CDN.
// Run: node scripts/build-radio-engine.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const pkgPath = require.resolve('hls.js/package.json');
const { version } = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
const js = fs.readFileSync(path.join(path.dirname(pkgPath), 'dist/hls.light.min.js'), 'utf8');
const out = path.join(root, 'src/components/radio/hlsEngine.generated.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Generated by scripts/build-radio-engine.mjs. hls.js ${version} light build (Apache-2.0), bundled for offline use.\n` +
    `export const HLS_JS = ${JSON.stringify(js)};\n`
);
console.log(`wrote ${path.relative(root, out)} (hls.js ${version}, ${Math.round(js.length / 1024)} KB)`);
